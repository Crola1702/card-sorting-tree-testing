-- Data collection for card sorting and tree testing.
-- Participants (anon) may only INSERT. Nobody but service_role can read.

create table public.participants (
  id uuid primary key, -- generated by the browser so results can reference it without reading back
  study_id text not null check (study_id ~ '^[A-Za-z0-9_-]{1,64}$'),
  country_or_section text not null check (char_length(btrim(country_or_section)) between 1 and 100),
  years_in_ieee smallint not null check (years_in_ieee between 0 and 70),
  was_branch_officer boolean not null,
  created_at timestamptz not null default now()
);

create table public.card_sort_placements (
  id bigint generated always as identity primary key,
  participant_id uuid not null references public.participants (id) on delete cascade,
  study_id text not null check (study_id ~ '^[A-Za-z0-9_-]{1,64}$'),
  group_name text not null check (char_length(btrim(group_name)) between 1 and 100),
  card_id text not null check (char_length(card_id) between 1 and 100),
  card_label text not null check (char_length(card_label) between 1 and 300),
  created_at timestamptz not null default now()
);

create table public.tree_test_results (
  id bigint generated always as identity primary key,
  participant_id uuid not null references public.participants (id) on delete cascade,
  study_id text not null check (study_id ~ '^[A-Za-z0-9_-]{1,64}$'),
  task_id text not null check (char_length(task_id) between 1 and 100),
  task_text text not null check (char_length(task_text) between 1 and 1000),
  path_ids text[] not null check (cardinality(path_ids) between 1 and 500),
  path_labels text[] not null check (cardinality(path_labels) = cardinality(path_ids)),
  selected_node_id text not null check (char_length(selected_node_id) between 1 and 100),
  selected_label text not null check (char_length(selected_label) between 1 and 300),
  correct boolean not null,
  backtrack_count integer not null check (backtrack_count between 0 and 500),
  backtracked boolean generated always as (backtrack_count > 0) stored,
  time_to_first_click_ms integer not null check (time_to_first_click_ms >= 0),
  hesitated boolean not null,
  duration_ms integer not null check (duration_ms >= 0),
  created_at timestamptz not null default now()
);

create index on public.card_sort_placements (participant_id);
create index on public.tree_test_results (participant_id);

alter table public.participants enable row level security;
alter table public.card_sort_placements enable row level security;
alter table public.tree_test_results enable row level security;

-- Supabase grants everything on public tables to anon/authenticated by default; narrow it to INSERT.
revoke all on public.participants, public.card_sort_placements, public.tree_test_results
  from anon, authenticated;
grant insert on public.participants, public.card_sort_placements, public.tree_test_results to anon;

-- Validation lives in the CHECK constraints above; there is deliberately no SELECT/UPDATE/DELETE policy.
create policy "anon insert only" on public.participants for insert to anon with check (true);
create policy "anon insert only" on public.card_sort_placements for insert to anon with check (true);
create policy "anon insert only" on public.tree_test_results for insert to anon with check (true);

-- Flat views for CSV export (read with the service role key only).
create view public.export_card_sort with (security_invoker = true) as
select
  c.id as row_id,
  p.study_id,
  p.id as participant_id,
  p.country_or_section,
  p.years_in_ieee,
  p.was_branch_officer,
  c.group_name,
  c.card_id,
  c.card_label,
  c.created_at
from public.card_sort_placements c
join public.participants p on p.id = c.participant_id;

create view public.export_tree_test with (security_invoker = true) as
select
  t.id as row_id,
  p.study_id,
  p.id as participant_id,
  p.country_or_section,
  p.years_in_ieee,
  p.was_branch_officer,
  t.task_id,
  t.task_text,
  array_to_string(t.path_labels, ' > ') as path,
  array_to_string(t.path_ids, ' > ') as path_ids,
  t.selected_node_id,
  t.selected_label,
  t.correct,
  t.backtracked,
  t.backtrack_count,
  t.hesitated,
  t.time_to_first_click_ms,
  t.duration_ms,
  t.created_at
from public.tree_test_results t
join public.participants p on p.id = t.participant_id;

revoke all on public.export_card_sort, public.export_tree_test from anon, authenticated;
